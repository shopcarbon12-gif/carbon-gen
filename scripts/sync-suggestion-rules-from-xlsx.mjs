#!/usr/bin/env node
/**
 * Reads `suggestion_rules.xlsx` (sheet Rules_Wide) and regenerates:
 * - `lib/shopcarbonSuggestionRulesData.ts`
 * - `data/shopcarbon_suggestion_rules.csv` (mirror for diff/review)
 *
 * Usage:
 *   node scripts/sync-suggestion-rules-from-xlsx.mjs [path-to-xlsx]
 *
 * Default: data/suggestion_rules.xlsx (copy Dropbox file there), else env SUGGESTION_RULES_XLSX.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import XLSX from "xlsx";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");

const COLLECTION_PREFIX = /^collection:\s*/i;

/** Same rules as `normalizeMenuPath` in `lib/shopifyCollectionSkuParser.ts` — keeps Excel rows aligned with auto-mapped paths. */
function normalizeMenuPath(value) {
  const text = String(value ?? "").trim();
  if (!text) return "";
  return text
    .replace(/[\\/_]+/g, " ")
    .replace(/\s*>\s*/g, " > ")
    .replace(/\s+/g, " ")
    .trim()
    .toUpperCase();
}

function defaultXlsxPath() {
  const env = String(process.env.SUGGESTION_RULES_XLSX || "").trim();
  if (env) return env;
  const dataPath = path.join(root, "data", "suggestion_rules.xlsx");
  if (fs.existsSync(dataPath)) return dataPath;
  const dropbox = path.join(
    process.env.USERPROFILE || "",
    "CARBON JEANS COMPANY Dropbox",
    "Marketing",
    "elior",
    "APP.SHOPCARBON.COM",
    "COLLECTION MAPPING MODULE",
    "suggestion_rules.xlsx"
  );
  if (fs.existsSync(dropbox)) return dropbox;
  return dataPath;
}

function slugPart(s) {
  return String(s || "")
    .replace(/[^a-z0-9]+/gi, "-")
    .replace(/^-|-$/g, "")
    .toLowerCase()
    .slice(0, 48);
}

function parseCell(raw) {
  const t = String(raw ?? "").trim();
  if (!t) return null;
  const m = t.match(COLLECTION_PREFIX);
  if (m) {
    const handle = t.slice(m[0].length).trim().toLowerCase();
    return handle ? { kind: "collection", value: handle } : null;
  }
  const normalizedPath = normalizeMenuPath(t);
  return normalizedPath ? { kind: "path", value: normalizedPath } : null;
}

function escapeTsString(s) {
  return JSON.stringify(s);
}

function main() {
  const xlsxPath = path.resolve(process.argv[2] || defaultXlsxPath());
  if (!fs.existsSync(xlsxPath)) {
    console.error("Missing xlsx:", xlsxPath);
    console.error("Copy suggestion_rules.xlsx to data/suggestion_rules.xlsx or pass path as argv[2].");
    process.exit(1);
  }

  const wb = XLSX.readFile(xlsxPath);
  const sheetName = wb.SheetNames.includes("Rules_Wide") ? "Rules_Wide" : wb.SheetNames[0];
  const sheet = wb.Sheets[sheetName];
  const matrix = XLSX.utils.sheet_to_json(sheet, { header: 1, defval: "" });

  if (!matrix.length) {
    console.error("Empty sheet");
    process.exit(1);
  }

  const rows = [];
  for (let i = 1; i < matrix.length; i++) {
    const row = matrix[i];
    const gender = String(row[0] ?? "").trim();
    const sourceCategory = normalizeMenuPath(row[1]);
    if (!sourceCategory) continue;

    const menuPaths = [];
    const directCollections = [];
    for (let c = 2; c <= 8; c++) {
      const parsed = parseCell(row[c]);
      if (!parsed) continue;
      if (parsed.kind === "collection") directCollections.push(parsed.value);
      else menuPaths.push(parsed.value);
    }

    const id = `xlsx-${slugPart(gender)}-${slugPart(sourceCategory)}-${i}`;
    rows.push({ id, gender, sourceCategory, menuPaths, directCollections });
  }

  // CSV mirror (same shape as before: Gender + base + up to 7 suggestion cells, raw text)
  const csvLines = [
    "Gender,Auto_Mapping_Path,Suggested_Path_1,Suggested_Path_2,Suggested_Path_3,Suggested_Path_4,Suggested_Path_5,Suggested_Path_6,Suggested_Path_7",
  ];
  for (let i = 1; i < matrix.length; i++) {
    const row = matrix[i];
    const gender = String(row[0] ?? "").trim();
    const source = String(row[1] ?? "").trim();
    if (!source) continue;
    const cells = [gender, source];
    for (let c = 2; c <= 8; c++) cells.push(String(row[c] ?? "").trim());
    csvLines.push(cells.map((v) => `"${String(v).replace(/"/g, '""')}"`).join(","));
  }
  const csvOut = path.join(root, "data", "shopcarbon_suggestion_rules.csv");
  fs.writeFileSync(csvOut, csvLines.join("\n") + "\n", "utf8");

  const tsPieces = [];
  tsPieces.push(`/**
 * Canonical ShopCarbon collection suggestion rows — generated by
 * \`npm run sync:suggestion-rules\` from \`data/suggestion_rules.xlsx\` (sheet Rules_Wide).
 *
 * Each row: match normalized base path (\`basePaths\`) after barcode auto-map, then emit
 * \`menuPaths\` and/or \`directCollections\` (Shopify handles) in column order.
 *
 * Cells prefixed with \`collection: \` become direct collection suggestions; otherwise menu paths.
 */
export type ShopcarbonSuggestionRuleRow = {
  id: string;
  gender: string;
  basePaths: string[];
  menuPaths: string[];
  /** Shopify collection handles (lowercase) for direct-assignment suggestion chips */
  directCollections: string[];
};

export const SHOPCARBON_SUGGESTION_RULE_ROWS: ShopcarbonSuggestionRuleRow[] = [
`);

  for (const r of rows) {
    const menuJs =
      r.menuPaths.length > 0
        ? `[\n${r.menuPaths.map((p) => `      ${escapeTsString(p)}`).join(",\n")}\n    ]`
        : `[]`;
    const dirJs =
      r.directCollections.length > 0
        ? `[\n${r.directCollections.map((h) => `      ${escapeTsString(h)}`).join(",\n")}\n    ]`
        : `[]`;
    tsPieces.push(`  {
    id: ${escapeTsString(r.id)},
    gender: ${escapeTsString(r.gender)},
    basePaths: [${escapeTsString(r.sourceCategory)}],
    menuPaths: ${menuJs},
    directCollections: ${dirJs},
  },
`);
  }

  tsPieces.push(`];
`);

  const tsOut = path.join(root, "lib", "shopcarbonSuggestionRulesData.ts");
  fs.writeFileSync(tsOut, tsPieces.join(""), "utf8");

  const dataCopy = path.join(root, "data", "suggestion_rules.xlsx");
  if (path.resolve(xlsxPath) !== path.resolve(dataCopy)) {
    fs.copyFileSync(xlsxPath, dataCopy);
    console.log("Copied xlsx ->", path.relative(root, dataCopy));
  }

  console.log("Wrote", path.relative(root, tsOut));
  console.log("Wrote", path.relative(root, csvOut));
  console.log("Rows:", rows.length, "(sheet:", sheetName + ")");
}

main();
